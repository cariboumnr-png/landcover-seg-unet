'''
Canonical data blocks catalog and metadata typing utilities.

Defines the core data structures used to represent, validate, and
serialize a catalog of spatial data blocks generated by geospatial
data preparation pipelines.

Public APIs:
    - `DatasetBlockMeta`: TypedDict describing block metadata.
    - `DatasetCatalog`: Mapping container for spatial block metadata.
'''

# standard imports
from __future__ import annotations
import collections.abc
import json
import re
import typing


# ----- public types
class DatasetBlockMeta(typing.TypedDict):
    '''
    Typed dictionary representing metadata for a single data block.

    Each entry captures both structural and provenance information
    required to uniquely identify, validate, and reproduce a block.
    '''
    block_name: str
    file_path: str
    row_col: list[int]
    valid_px_ratios: dict[str, float]
    class_count: dict[str, list[int]]
    schema_version: str
    creation_time: str
    sha_256: str
    aligned_grid: str
    source_image: str
    source_image_sha_256: str
    source_label: str | None
    source_label_sha_256: str | None


# ----- public classes
class DatasetCatalog(collections.abc.Mapping[tuple[int, int], DatasetBlockMeta]):
    '''
    Mapping container for managing spatial block metadata.

    Maps (row, col) coordinate tuples to `DatasetBlockMeta` objects,
    providing dictionary-like access and deterministic serialization.

    Schema: SCHEMA_ID = 'data_catalog_payload/v1'
    '''

    SCHEMA_ID: str = 'data_catalog_payload/v1'

    def __init__(self) -> None:
        '''Initialize an empty DatasetCatalog instance.'''
        self._data: dict[tuple[int, int], DatasetBlockMeta] = {}

    def __getitem__(self, key: tuple[int, int]) -> DatasetBlockMeta:
        return self._data[key]

    def __setitem__(
        self,
        key: tuple[int, int],
        value: DatasetBlockMeta
    ) -> None:
        self._data[key] = value

    def __iter__(self) -> collections.abc.Iterator[tuple[int, int]]:
        return iter(self._data)

    def __len__(self) -> int:
        return len(self._data)

    @classmethod
    def from_dict(
        cls,
        source: dict[str, DatasetBlockMeta]
    ) -> DatasetCatalog:
        '''
        Construct a DatasetCatalog from a dictionary representation.

        Converts string-encoded coordinate keys back into (row, col)
        coordinate tuples.

        Args:
            source:
                dictionary mapping keys to DatasetCatalogEntry objects.

        Returns:
            DatasetCatalog:
                a populated DatasetCatalog instance.
        '''
        def _name_xy(name: str) -> tuple[int, int]:
            # e.g.,  row_000034_col_000012 -> (12, 34)
            split = name.split('_')
            y_str, x_str = split[1], split[3]
            return int(x_str), int(y_str)

        obj = cls.__new__(cls)
        obj._data = {_name_xy(k): v for k, v in source.items()}
        return obj

    def to_json_payload(self) -> str:
        '''
        Serialize the catalog to a deterministically ordered JSON string.

        Formats output with stable key ordering and compact array
        formatting.

        Returns:
            str:
                formatted JSON string payload.
        '''
        def _xy_name(coords: tuple[int, int]) -> str:
            '''Format coordinate tuple as row/col string.'''
            x, y = coords
            return f'row_{y:06d}_col_{x:06d}'

        # sort self._data and start the line
        data = {_xy_name(k): v for k, v in self._data.items()}

        # raw json and custom formatting before return
        raw_json = json.dumps(data, indent=4)
        # make list of numbers to be on the same line
        _json = re.sub(r'\n\s+(\d+)', r' \1', raw_json) # remove new lines
        _json = re.sub(r'\[ ', r'[', _json) # fix leading bracket
        _json = re.sub(r'\n\s+\]', r']', _json) # fix closing bracket
        return _json
